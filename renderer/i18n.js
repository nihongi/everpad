  /* Windows の表示言語などから、使う言語を決める(日本語以外は英語) */
  function pick(locale) { return /^ja\b/i.test(String(locale || '')) ? 'ja' : 'en'; }

  function t(lang, key, params) {
    const d = DICT[lang] || DICT.ja;
    let v = d[key];
    if (v === undefined) v = DICT.ja[key];
    if (v === undefined) return key;
    const p = params || {};
    if (typeof v === 'function') return v(p);
    return v.replace(/\{(\w+)\}/g, (m, k) => (p[k] !== undefined ? String(p[k]) : m));
  }

